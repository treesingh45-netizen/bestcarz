import { getStoredOwnerListings, ownerListingToVehicle } from './marketplaceStorage';

export function getAllInventory(): Vehicle[] {
  const publishedOwnerVehicles = getStoredOwnerListings()
    .filter((l) => l.status === 'Published' || l.status === 'Under Offer')
    .map(ownerListingToVehicle);

  return [
    ...SHOWROOM_INVENTORY.map((v) => ({ ...v, inventoryType: 'showroom' as const })),
    ...SAMPLE_CATALOG_INVENTORY,
    ...publishedOwnerVehicles,
  ];
}

